import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { createApp } from '../server.js';
const server = createApp({}, false).listen(0, '127.0.0.1');
await new Promise(resolve => server.once('listening', resolve));
let browser;
try {
  browser = await chromium.launch({ headless: true, ...(process.env.BROWSER_EXECUTABLE ? { executablePath: process.env.BROWSER_EXECUTABLE } : {}) });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1050 } });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(`http://127.0.0.1:${server.address().port}`);
  await page.locator('#setup:visible').waitFor();
  assert.equal(await page.locator('.welcome h1').textContent(), 'Cook ideas.');
  assert.equal(await page.locator('.message').count(), 0);
  await page.screenshot({ path: '/tmp/sauceygpt-welcome.png', fullPage: true });
  const result = { type: 'result', blocks: [[{ text: 'This claim has evidence.', citations: [1] }, { text: ' This is uncited.' }]], answer: 'This claim has evidence.', notice: 'Supporting references found after the draft.', provider: 'OpenAI web search', sources: [{ id: 1, title: '<script>alert(1)</script>', url: 'https://example.org/', format: 'html', readStatus: 'read', evidence: [{ claim: 'This claim has evidence.', quote: 'This is the exact supporting passage.', page: null, locationURL: 'https://example.org/#:~:text=This%20is%20the%20exact%20supporting%20passage.' }] }] };
  await page.route('**/api/chat', route => route.fulfill({ contentType: 'application/x-ndjson', body: JSON.stringify({ type: 'draft_delta', delta: 'Preliminary answer' }) + '\n' + JSON.stringify(result) + '\n' }));
  await page.locator('#question').fill('What is the evidence?'); await page.locator('#send').click();
  await page.locator('.citation').waitFor();
  assert.equal(await page.locator('.citation').getAttribute('href'), 'https://example.org/');
  assert.equal(await page.locator('.citation').getAttribute('target'), '_blank');
  assert.equal(await page.locator('.source script').count(), 0);
  assert.equal(await page.locator('.source').isVisible(), true);
  assert.equal(await page.locator('.sources summary').count(), 0);
  await page.locator('.citation').click();
  await page.locator('#evidence-dialog[open]').waitFor();
  assert.equal(await page.locator('#evidence-dialog blockquote').textContent(), '“This is the exact supporting passage.”');
  assert.match(await page.locator('.passage-link').getAttribute('href'), /#:~:text=/);
  assert.equal(await page.locator('#evidence-dialog script').count(), 0);
  await page.screenshot({ path: '/tmp/sauceygpt-excerpt.png', fullPage: true });
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('#evidence-dialog').isVisible(), false);
  await page.locator('.reference-link').click();
  await page.locator('#evidence-dialog[open]').waitFor();
  await page.locator('#close-evidence').click();
  assert.match(await page.locator('.source').innerText(), /<script>alert/);
  assert.equal(await page.locator('.cited-claim').textContent(), 'This claim has evidence.');
  assert.equal(await page.locator('.cited-claim').evaluate(el => getComputedStyle(el).textDecorationLine), 'underline');
  assert.equal(await page.locator('.citation').textContent(), '[1]');
  assert.equal(await page.locator('.citation').evaluate(el => getComputedStyle(el).color), 'rgb(37, 92, 179)');
  assert.equal(await page.locator('.cited-claim').evaluate(el => getComputedStyle(el).color), 'rgb(56, 47, 40)');
  assert.equal(await page.locator('.answer-label').count(), 0);
  await page.screenshot({ path: '/tmp/sauceygpt-answer.png', fullPage: true });
  await page.reload();
  await page.locator('.welcome').waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: '/tmp/sauceygpt-mobile.png', fullPage: true });
  assert.deepEqual(errors, []);
  console.log('Browser checks passed: desktop, mobile, readable text and blue citation markers, safe rendering, sauce jar welcome, expanded references, excerpt dialogs, and an empty initial conversation. Screenshots: /tmp/sauceygpt-{desktop,answer,mobile}.png');
} finally { await browser?.close(); server.close(); }
